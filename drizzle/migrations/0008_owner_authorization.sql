-- Add a UID-based owner identity without changing or deleting existing users/roles.
CREATE TABLE IF NOT EXISTS public.owner_accounts (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.owner_accounts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.owner_accounts FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.owner_accounts TO service_role;

CREATE OR REPLACE FUNCTION public.is_owner()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.owner_accounts WHERE user_id = auth.uid()
  );
$$;
REVOKE ALL ON FUNCTION public.is_owner() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_owner() TO authenticated;

-- Keep existing content editor access for admins and the owner, but make the owner
-- independently identifiable and able to administer the platform.
DROP POLICY IF EXISTS "Owners read drafts" ON public.content_drafts;
DROP POLICY IF EXISTS "Owners insert drafts" ON public.content_drafts;
DROP POLICY IF EXISTS "Owners update drafts" ON public.content_drafts;
DROP POLICY IF EXISTS "Owners delete drafts" ON public.content_drafts;
CREATE POLICY "Admins and owner read drafts" ON public.content_drafts FOR SELECT TO authenticated
  USING (public.is_owner() OR public.has_role(auth.uid(), 'admin'));
CREATE POLICY "Admins and owner insert drafts" ON public.content_drafts FOR INSERT TO authenticated
  WITH CHECK (public.is_owner() OR public.has_role(auth.uid(), 'admin'));
CREATE POLICY "Admins and owner update drafts" ON public.content_drafts FOR UPDATE TO authenticated
  USING (public.is_owner() OR public.has_role(auth.uid(), 'admin'))
  WITH CHECK (public.is_owner() OR public.has_role(auth.uid(), 'admin'));
CREATE POLICY "Admins and owner delete drafts" ON public.content_drafts FOR DELETE TO authenticated
  USING (public.is_owner() OR public.has_role(auth.uid(), 'admin'));

CREATE TABLE IF NOT EXISTS public.admin_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  action text NOT NULL CHECK (char_length(action) BETWEEN 1 AND 100),
  target_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.admin_activity ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admin_activity FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.admin_activity TO authenticated;
GRANT ALL ON TABLE public.admin_activity TO service_role;
DROP POLICY IF EXISTS "Owner reads admin activity" ON public.admin_activity;
CREATE POLICY "Owner reads admin activity" ON public.admin_activity FOR SELECT TO authenticated
  USING (public.is_owner());

-- No client may assign itself a role. Only the UID explicitly bootstrapped as
-- owner may add/remove admin. The owner cannot be modified through this RPC.
CREATE OR REPLACE FUNCTION public.set_admin_role(_target_user_id uuid, _enabled boolean)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_owner() THEN
    RAISE EXCEPTION 'owner access required' USING ERRCODE = '42501';
  END IF;
  IF _target_user_id IS NULL OR _enabled IS NULL THEN
    RAISE EXCEPTION 'target user and enabled flag are required' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM public.owner_accounts WHERE user_id = _target_user_id) THEN
    RAISE EXCEPTION 'owner permissions cannot be changed through admin role management' USING ERRCODE = '42501';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM auth.users WHERE id = _target_user_id) THEN
    RAISE EXCEPTION 'target user does not exist' USING ERRCODE = '22023';
  END IF;

  IF _enabled THEN
    INSERT INTO public.user_roles (user_id, role) VALUES (_target_user_id, 'admin')
    ON CONFLICT (user_id, role) DO NOTHING;
  ELSE
    DELETE FROM public.user_roles WHERE user_id = _target_user_id AND role = 'admin';
  END IF;

  INSERT INTO public.admin_activity (actor_id, action, target_user_id, details)
  VALUES (auth.uid(), CASE WHEN _enabled THEN 'admin.grant' ELSE 'admin.revoke' END,
          _target_user_id, jsonb_build_object('enabled', _enabled));
END;
$$;
REVOKE ALL ON FUNCTION public.set_admin_role(uuid, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_admin_role(uuid, boolean) TO authenticated;

CREATE OR REPLACE FUNCTION public.owner_dashboard_stats()
RETURNS TABLE (total_users bigint, total_admins bigint, published_modules bigint, recent_admin_actions bigint)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_owner() THEN
    RAISE EXCEPTION 'owner access required' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
    SELECT (SELECT count(*) FROM auth.users),
           (SELECT count(DISTINCT user_id) FROM public.user_roles WHERE role = 'admin'),
           (SELECT count(*) FROM public.content_published WHERE kind = 'module'),
           (SELECT count(*) FROM public.admin_activity WHERE created_at >= now() - interval '30 days');
END;
$$;
REVOKE ALL ON FUNCTION public.owner_dashboard_stats() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.owner_dashboard_stats() TO authenticated;

